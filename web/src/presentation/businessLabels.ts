export function businessLabel(value: unknown): string {
  if (value === null || value === undefined || value === "") return "기록 없음";
  const text = String(value);
  return labels[text] ?? text.replaceAll("_", " ").toLocaleLowerCase("ko-KR");
}

export function operationalReference(value: string): string {
  return value.replaceAll("-DEMO", "").replace(/^DEMO-/, "CS-");
}

